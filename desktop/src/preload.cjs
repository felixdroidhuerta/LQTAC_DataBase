const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('lqtac', Object.freeze({
  writeClipboard: text => ipcRenderer.invoke('clipboard:write',text),
  openSQL: () => ipcRenderer.invoke('sql:open'),
  saveSQL: request => ipcRenderer.invoke('sql:save',request),
  listConnections: () => ipcRenderer.invoke('connections:list'),
  saveConnection: profile => ipcRenderer.invoke('connections:save', profile),
  connectionOverview: () => ipcRenderer.invoke('connections:overview'),
  createConnectionGroup: (name, ids) => ipcRenderer.invoke('connections:create-group', name, ids),
  moveConnections: (ids, groupId) => ipcRenderer.invoke('connections:move', ids, groupId),
  ungroupConnections: id => ipcRenderer.invoke('connections:ungroup', id),
  activateConnection: key => ipcRenderer.invoke('connections:activate', key),
  disconnectConnection: key => ipcRenderer.invoke('connections:disconnect', key),
  removeConnections: ids => ipcRenderer.invoke('connections:remove', ids),
  connectProfile: (id, password) => ipcRenderer.invoke('connections:connect', id, password),
  testProfile: (id, password) => ipcRenderer.invoke('connections:test', id, password),
  disconnect: () => ipcRenderer.invoke('database:disconnect'),
  catalog: () => ipcRenderer.invoke('database:catalog'),
  selectDatabase: name => ipcRenderer.invoke('database:select', name),
  inspectTable: (schema, table) => ipcRenderer.invoke('table:inspect', schema, table),
  previewTable: request => ipcRenderer.invoke('table:preview', request),
  applyTable: token => ipcRenderer.invoke('table:apply', token),
  inspectTrigger: (schema, name) => ipcRenderer.invoke('trigger:inspect', schema, name),
  previewTrigger: request => ipcRenderer.invoke('trigger:preview', request),
  applyTrigger: token => ipcRenderer.invoke('trigger:apply', token),
  demo: () => ipcRenderer.invoke('database:demo'),
  open: () => ipcRenderer.invoke('database:open'),
  execute: (sql, sessionKey,limit,context) => ipcRenderer.invoke('database:execute', sql, sessionKey,limit,context),
  planExecution: (source,options,key) => ipcRenderer.invoke('query:plan',source,options,key),
  executeBatch: (statements,key,limit,context,runId) => ipcRenderer.invoke('database:batch',statements,key,limit,context,runId),
  onExecutionProgress: callback => {const handler=(_event,data)=>callback(data);ipcRenderer.on('execution:progress',handler);return ()=>ipcRenderer.removeListener('execution:progress',handler);},
  formatQuery: (source,engine) => ipcRenderer.invoke('query:format',source,engine),
  columns: (tables,key) => ipcRenderer.invoke('database:columns',tables,key),
  restoreContext: (key,context) => ipcRenderer.invoke('database:context',key,context),
  inspectObject: (target,key) => ipcRenderer.invoke('object:inspect',target,key),
  previewObject: (request,key) => ipcRenderer.invoke('object:preview',request,key),
  applyObject: (token,key) => ipcRenderer.invoke('object:apply',token,key),
  relations: (schema,sessionKey) => ipcRenderer.invoke('database:relations',schema,sessionKey),
  exportResult: (token,index,format,indices) => ipcRenderer.invoke('results:export',token,index,format,indices),
  export: () => ipcRenderer.invoke('database:export'),
  status: () => ipcRenderer.invoke('database:status')
}));
