const {app,BrowserWindow}=require('electron'),assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {startMySQLFixture}=require('./mysql-fixture.cjs');
app.setPath('userData',fs.mkdtempSync(path.join(os.tmpdir(),'dbfox-connect-all-')));
app.on('browser-window-created',(_e,w)=>{w.hide();w.webContents.setBackgroundThrottling(false);});
require('../src/main.cjs');
const timeout=setTimeout(()=>{console.error('Connect all timed out');app.exit(1);},40000);
app.whenReady().then(async()=>{
 const w=BrowserWindow.getAllWindows()[0],fixture=await startMySQLFixture(),js=code=>w.webContents.executeJavaScript(code);
 const until=expression=>js(`new Promise((resolve,reject)=>{const start=Date.now();function poll(){if(${expression})return resolve();if(Date.now()-start>10000)return reject(Error('Timeout: '+${JSON.stringify(expression)}));setTimeout(poll,40)}poll()})`);
 try{
  if(w.webContents.isLoading())await new Promise(r=>w.webContents.once('did-finish-load',r));
  const profiles=[];
  for(const name of ['Guardada','Pedir contraseña','Omitir'])profiles.push(await js(`window.lqtac.saveConnection(${JSON.stringify({...fixture.profile,name})})`));
  await js(`window.lqtac.connectProfile(${JSON.stringify(profiles[0].id)},'fixture-test-password',true)`);
  await js(`window.lqtac.disconnectConnection(${JSON.stringify(profiles[0].id)})`);
  const initial=await js(`document.querySelectorAll('#query-tabs .query-tab').length`);
  await js(`document.querySelector('[data-view=connections]').click()`);
  await until(`document.querySelectorAll('.profile-row').length===3`);
  assert.equal(await js(`document.querySelector('#refresh-explorer').nextElementSibling.id`),'connect-all-side');
  assert.equal(await js(`document.querySelector('#connect-all-side').title`),'Conectar todos');
  await js(`document.querySelector('#connect-all-side').click()`);
  await until(`document.querySelector('#credentials-dialog').open`);
  assert.equal(await js(`document.querySelector('#credentials-heading').textContent`),'Conectar a Pedir contraseña');
  assert.equal(await js(`document.querySelector('#connect-all-side').disabled`),true);
  await js(`document.querySelector('#connection-password').value='fixture-test-password';document.querySelector('#credentials-form').requestSubmit()`);
  await until(`document.querySelector('#credentials-dialog').open && document.querySelector('#credentials-heading').textContent==='Conectar a Omitir'`);
  await js(`document.querySelector('#cancel-credentials').click()`);
  await until(`!document.querySelector('#connect-all').disabled`);
  assert.equal(await js(`document.querySelector('#connect-all-side').disabled`),false);
  assert.equal((await js('window.lqtac.connectionOverview()')).sessions.filter(x=>x.connected).length,2);
  await until(`Array.from(document.querySelectorAll('.connection-row')).filter(r=>r.querySelector('.power-on')).length===2`);
  assert.equal(await js(`Array.from(document.querySelectorAll('.connection-row')).every(r=>r.getAttribute('aria-expanded')==='false')`),true);
  await js(`document.querySelector('.connection-row .connection-expand').click()`);
  await until(`document.querySelector('.schema-tree')`);
  assert.equal(await js(`Array.from(document.querySelectorAll('.schema-tree,.object-group')).every(node=>!node.open)`),true);
  await js(`document.querySelector('.schema-tree summary').click()`);
  await until(`document.querySelector('.schema-tree').open`);
  await js(`document.querySelector('#refresh-explorer').click()`);
  await until(`!document.querySelector('#refresh-explorer').disabled`);
  assert.equal(await js(`document.querySelector('.schema-tree').open`),true);
  assert.equal(await js(`document.querySelectorAll('#query-tabs .query-tab').length`),initial);
  assert.equal(await js(`document.querySelector('#connections').classList.contains('hidden')`),false);
  await js(`document.querySelector('#connect-all').click()`);
  await until(`document.querySelector('#credentials-dialog').open`);
  assert.equal(await js(`document.querySelector('#credentials-heading').textContent`),'Conectar a Omitir');
  await js(`document.querySelector('#connection-password').value='fixture-test-password';document.querySelector('#credentials-form').requestSubmit()`);
  await until(`!document.querySelector('#connect-all').disabled`);
  assert.equal((await js('window.lqtac.connectionOverview()')).sessions.filter(x=>x.connected).length,3);
  assert.equal(await js(`document.querySelectorAll('#query-tabs .query-tab').length`),initial);
  await js(`window.lqtac.disconnectConnection(${JSON.stringify(profiles[2].id)})`);
  await js(`document.querySelector('[data-view=connections]').click()`);
  await until(`Array.from(document.querySelectorAll('.profile-row')).find(r=>r.querySelector('h3').textContent==='Omitir')?.querySelector('.primary').textContent==='Conectar'`);
  await js(`Array.from(document.querySelectorAll('.profile-row')).find(r=>r.querySelector('h3').textContent==='Omitir').querySelector('.primary').click()`);
  await until(`document.querySelector('#credentials-dialog').open`);
  await js(`document.querySelector('#connection-password').value='fixture-test-password';document.querySelector('#credentials-form').requestSubmit()`);
  await until(`!document.querySelector('#credentials-dialog').open`);
  assert.equal(await js(`document.querySelectorAll('#query-tabs .query-tab').length`),initial);
  await js(`document.querySelector('#new-query').click()`);
  await until(`document.querySelectorAll('#query-tabs .query-tab').length===${initial+1}`);
  assert.equal(JSON.parse(await js(`localStorage.getItem('lqtac.queries')`)).at(-1).connectionKey,profiles[2].id);
  console.log('PASS: connect all, saved credentials, prompting, cancellation, existing-session skip, no automatic query and explicit new query');
  clearTimeout(timeout);await fixture.close();app.exit(0);
 }catch(error){console.error(error);clearTimeout(timeout);await fixture.close();app.exit(1);}
});
