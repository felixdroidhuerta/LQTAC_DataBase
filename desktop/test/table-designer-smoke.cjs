const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const { mkdtempSync, readdirSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join } = require('node:path');
const { startMySQLFixture } = require('./mysql-fixture.cjs');
app.setPath('userData', mkdtempSync(join(tmpdir(), 'lqtac-designer-smoke-')));
require('../src/main.cjs');
const timeout = setTimeout(() => { console.error('Table designer test timed out'); app.exit(1); }, 30000);
app.whenReady().then(async () => {
  const window = BrowserWindow.getAllWindows()[0];
  const fixture = await startMySQLFixture();
  const js = code => window.webContents.executeJavaScript(code);
  const until = expression => js(`new Promise((resolve,reject)=>{const start=Date.now(); const poll=()=>{if(${expression})return resolve();if(Date.now()-start>10000)return reject(new Error('Designer condition timed out'));setTimeout(poll,40)};poll()})`);
  try {
    if (window.webContents.isLoading()) await new Promise(resolve => window.webContents.once('did-finish-load', resolve));
    await js(`window.lqtac.saveConnection(${JSON.stringify(fixture.profile)})`);
    await js(`document.querySelector('.rail-button[data-view=connections]').click()`);
    await until("document.querySelector('.profile-row .primary')");
    await js(`document.querySelector('.profile-row .primary').click()`);
    await until("document.querySelector('#credentials-dialog').open");
    await js(`document.querySelector('#connection-password').value='fixture-test-password';document.querySelector('#credentials-form').requestSubmit()`);
    await until("document.querySelector('.edit-table[data-schema=test]') && !document.querySelector('#run-query').disabled");
    await js(`document.querySelector('.edit-table[data-schema=test][data-table=proyectos]').click()`);
    await until("document.querySelector('#designer-title').textContent==='test.proyectos' && !document.querySelector('#preview-table').disabled");
    assert.equal(await js('document.querySelectorAll(".structure-table tbody tr").length'), 2);
    assert.equal(await js('document.querySelector("[data-column=\\"0\\"] [data-field=primary]").checked'), true);
    await js(`document.querySelector('.structure-actions button').click();
      const row=document.querySelector('.structure-table tbody tr:last-child');
      const name=row.querySelector('[data-field=name]');name.value='notas';name.dispatchEvent(new Event('input'));
      const type=row.querySelector('[data-field=type]');type.value='TEXT';type.dispatchEvent(new Event('input'));
      document.querySelector('#preview-table').click();`);
    await until("document.querySelector('#table-review-dialog').open && !document.querySelector('#apply-table').disabled");
    assert.match(await js('document.querySelector("#table-review-sql").textContent'), /ADD COLUMN `notas` TEXT NULL/);
    assert.equal(fixture.queries.filter(sql => sql.startsWith('ALTER TABLE')).length, 0);
    await js(`document.querySelector('#apply-table').click();document.querySelector('#apply-table').click()`);
    await until("!document.querySelector('#table-review-dialog').open && document.querySelectorAll('.structure-table tbody tr').length===3 && !document.querySelector('#preview-table').disabled");
    assert.equal(fixture.queries.filter(sql => sql.startsWith('ALTER TABLE')).length, 1);
    console.log('Designer: inspect, column edit, SQL review and single application passed');
    await js(`document.querySelector('[data-designer-pane=triggers]').click();document.querySelector('#designer-content .designer-object-head button').click()`);
    await until("document.querySelector('#trigger-editor-dialog').open && !document.querySelector('#review-trigger').disabled");
    assert.equal(await js('document.querySelector("#trigger-body").value'), 'SET NEW.nombre = TRIM(NEW.nombre)');
    await js(`(()=>{const body=document.querySelector('#trigger-body');body.value='SET NEW.nombre = UPPER(NEW.nombre)';body.dispatchEvent(new Event('input'));document.querySelector('#review-trigger').click()})()`);
    await until("!document.querySelector('#apply-trigger').classList.contains('hidden') && !document.querySelector('#apply-trigger').disabled");
    assert.match(await js('document.querySelector("#trigger-review-sql").textContent'), /DROP TRIGGER[\s\S]*CREATE DEFINER=/);
    assert.equal(fixture.queries.filter(sql=>sql.startsWith('DROP TRIGGER')).length, 0);
    await js(`document.querySelector('#apply-trigger').click()`);
    await until("!document.querySelector('#trigger-editor-dialog').open && document.querySelector('#designer-content').textContent.includes('UPPER')");
    assert.equal(fixture.queries.filter(sql=>sql.startsWith('DROP TRIGGER')).length, 1);
    assert.equal(readdirSync(join(app.getPath('userData'), 'trigger-backups')).length, 1);
    console.log('Designer: direct trigger update applied');
    await js(`document.querySelector('#designer-content .designer-object-head button').click()`);
    await until("document.querySelector('#trigger-editor-dialog').open && !document.querySelector('#review-trigger').disabled");
    await js(`(()=>{const body=document.querySelector('#trigger-body');body.value='INVALID_BODY';body.dispatchEvent(new Event('input'));document.querySelector('#review-trigger').click()})()`);
    await until("!document.querySelector('#apply-trigger').classList.contains('hidden') && !document.querySelector('#apply-trigger').disabled");
    await js(`document.querySelector('#apply-trigger').click()`);
    await until("document.querySelector('#trigger-editor-message').textContent.includes('se restauró') && !document.querySelector('#cancel-trigger').disabled");
    assert.equal((await js(`window.lqtac.inspectTrigger('test','audit_proyectos')`)).body, 'SET NEW.nombre = UPPER(NEW.nombre)');
    await js(`document.querySelector('#cancel-trigger').click()`);
    console.log('Designer: trigger edit, separate connection, backup and automatic restoration passed');
    await js(`document.querySelector('[data-designer-pane=indexes]').click();document.querySelector('#designer-content>button').click();document.querySelector('#preview-table').click()`);
    await until("document.querySelector('#table-review-dialog').open && !document.querySelector('#apply-table').disabled");
    assert.match(await js('document.querySelector("#table-review-sql").textContent'), /ADD INDEX `idx_nuevo`/);
    fixture.changeDefinition();
    await js(`document.querySelector('#apply-table').click()`);
    await until("document.querySelector('#table-apply-error').textContent.includes('cambiado')");
    assert.equal(fixture.queries.filter(sql => sql.startsWith('ALTER TABLE')).length, 1);
    await js(`document.querySelector('#cancel-table-review').click();window.confirm=()=>true;document.querySelector('#close-designer').click()`);
    await js(`document.querySelector('[aria-label="Crear tabla en test"]').click()`);
    await until("document.querySelector('#designer-title').textContent==='test.nueva_tabla' && !document.querySelector('#preview-table').disabled");
    await js(`document.querySelector('#preview-table').click()`);
    await until("document.querySelector('#table-review-dialog').open && !document.querySelector('#apply-table').disabled");
    assert.match(await js('document.querySelector("#table-review-sql").textContent'), /CREATE TABLE `test`\.`nueva_tabla`/);
    assert.equal(fixture.queries.filter(sql => sql.startsWith('CREATE TABLE')).length, 0);
    await js(`document.querySelector('#cancel-table-review').click()`);
    assert.equal(await js('document.body.scrollWidth <= innerWidth'), true);
    await fixture.close();
    console.log('PASS: direct trigger editor with recovery, table designer, column creation, index preview, explicit apply and stale-schema protection');
    clearTimeout(timeout); app.exit(0);
  } catch (error) { console.error(error); await fixture.close(); clearTimeout(timeout); app.exit(1); }
});
