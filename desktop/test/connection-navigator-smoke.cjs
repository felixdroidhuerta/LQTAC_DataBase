const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const { mkdtempSync, readFileSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join } = require('node:path');
const { startMySQLFixture } = require('./mysql-fixture.cjs');
app.setPath('userData', mkdtempSync(join(tmpdir(), 'lqtac-navigator-smoke-')));
require('../src/main.cjs');
const timeout = setTimeout(() => { console.error('Connection navigator test timed out'); app.exit(1); }, 40000);
app.whenReady().then(async () => {
  const window = BrowserWindow.getAllWindows()[0]; const fixture = await startMySQLFixture();
  const js = code => window.webContents.executeJavaScript(code);
  const until = expression => js(`new Promise((resolve,reject)=>{const start=Date.now();const poll=()=>{if(${expression})return resolve();if(Date.now()-start>10000)return reject(new Error('Navigator condition timed out: '+${JSON.stringify(expression)}));setTimeout(poll,40)};poll()})`);
  const row = id => `.connection-row[data-id="${id}"]`;
  const openMenu = id => js(`document.querySelector(${JSON.stringify(row(id))}).dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:150,clientY:220}))`);
  const menuClick = text => js(`[...document.querySelectorAll('#connection-context-menu button')].find(button=>button.textContent===${JSON.stringify(text)}).click()`);
  async function drag(id, target) {
    await js(`(()=>{const source=document.querySelector(${JSON.stringify(row(id))});source.click();const data=new DataTransfer();source.dispatchEvent(new DragEvent('dragstart',{bubbles:true,cancelable:true,dataTransfer:data}));document.querySelector(${JSON.stringify(target)}).dispatchEvent(new DragEvent('drop',{bubbles:true,cancelable:true,dataTransfer:data}));source.dispatchEvent(new DragEvent('dragend',{bubbles:true,dataTransfer:data}));})()`);
  }
  async function connect(id) {
    await js(`document.querySelector(${JSON.stringify(row(id)+' .connection-power')}).click()`);
    await until("document.querySelector('#credentials-dialog').open");
    assert.equal(await js('document.querySelector("#switch-dialog").open'), false);
    await js(`document.querySelector('#connection-password').value='fixture-test-password';document.querySelector('#credentials-form').requestSubmit()`);
    await until(`document.querySelector(${JSON.stringify(row(id)+' .power-on')}) && !document.querySelector('#run-query').disabled`);
  }
  try {
    if (window.webContents.isLoading()) await new Promise(resolve => window.webContents.once('did-finish-load', resolve));
    const a = await js(`window.lqtac.saveConnection(${JSON.stringify({ ...fixture.profile, name: 'Servidor A' })})`);
    const b = await js(`window.lqtac.saveConnection(${JSON.stringify({ ...fixture.profile, name: 'Servidor B', database: 'asterisk' })})`);
    const c = await js(`window.lqtac.saveConnection(${JSON.stringify({ ...fixture.profile, name: 'Servidor C' })})`);
    await js(`document.querySelector('#refresh-explorer').click()`);
    await until("document.querySelectorAll('.connection-row').length===3");
    assert.equal(await js('document.querySelectorAll(".connection-power.power-off").length'), 3);
    assert.equal(await js('document.querySelector("#workspace-panel").open'), false);
    assert.equal(await js('document.querySelectorAll(".nav[data-view=connections]").length'), 0);
    assert.equal(await js('document.querySelectorAll(".rail-button[data-view=connections]").length'), 1);
    await js(`document.querySelector(${JSON.stringify(row(a.id))}).click();document.querySelector(${JSON.stringify(row(b.id))}).dispatchEvent(new MouseEvent('click',{ctrlKey:true,bubbles:true}));document.dispatchEvent(new KeyboardEvent('keydown',{key:'G',code:'KeyG',ctrlKey:true,shiftKey:true,bubbles:true,cancelable:true}))`);
    assert.equal(await js('document.querySelector("#connection-group-dialog").open'), true);
    await js(`document.querySelector('#connection-group-name').value='Equipo';document.querySelector('#connection-group-form').requestSubmit()`);
    await until("document.querySelectorAll('.connection-group .connection-row').length===2");
    const group = (await js('window.lqtac.connectionOverview()')).groups[0];
    assert.deepEqual(new Set(group.connectionIds), new Set([a.id, b.id]));
    await openMenu(a.id);
    const labels = await js(`[...document.querySelectorAll('#connection-context-menu button')].map(button=>button.textContent)`);
    assert.ok(labels.includes('Conectar') && labels.includes('Añadir a grupo…') && labels.some(label=>label.startsWith('Agrupar')));
    await js(`document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`);
    await drag(b.id, '.ungrouped-connections');
    await until(`document.querySelector('.ungrouped-connections ${row(b.id)}')`);
    assert.deepEqual((await js('window.lqtac.connectionOverview()')).groups[0].connectionIds, [a.id]);
    await drag(b.id, '.connection-group');
    await until("document.querySelectorAll('.connection-group .connection-row').length===2");
    await openMenu(c.id); await menuClick('Añadir a grupo…');
    await js(`document.querySelector('#assign-group-target').value=${JSON.stringify(group.id)};document.querySelector('#assign-group-form').requestSubmit()`);
    await until("document.querySelectorAll('.connection-group .connection-row').length===3");
    await js('window.confirm=()=>true;void 0');
    await openMenu(c.id); await menuClick('Borrar');
    await until("document.querySelectorAll('.connection-row').length===2");
    assert.equal(JSON.parse(readFileSync(join(app.getPath('userData'),'connections-trash.json'),'utf8'))[0].id, c.id);
    await js(`document.querySelector('#workspace-panel>summary').click()`);
    await until("localStorage.getItem('lqtac.workspaceExpanded')==='true'");
    const reloaded = new Promise(resolve => window.webContents.once('did-finish-load', resolve)); window.webContents.reload(); await reloaded;
    await until("document.querySelectorAll('.connection-group .connection-row').length===2");
    assert.equal(await js('document.querySelector("#workspace-panel").open'), true);
    await js('window.confirm=()=>true;void 0');
    console.log('Navigator: rail, collapsed workspace, multi-selection, groups, drag in/out, menu assignment, archive and reload passed');
    await connect(a.id); await connect(b.id);
    assert.equal(await js('document.querySelectorAll(".power-on").length'), 2);
    assert.equal(await js('document.querySelector("#sessions-count").textContent'), '2');
    const queries = await js('JSON.parse(localStorage.getItem("lqtac.queries"))');
    const aTab = queries.find(tab=>tab.connectionKey===a.id);
    const bTab = queries.find(tab=>tab.connectionKey===b.id);
    assert.ok(aTab && bTab);
    await js(`document.querySelector('.query-tab[data-id="${aTab.id}"] .tab-select').click()`);
    await until("document.querySelector('#connection-label').textContent==='Servidor A' && !document.querySelector('#run-query').disabled");
    await js(`document.querySelector('#run-query').click()`);
    await until("document.querySelector('#results tbody td')?.textContent==='test'");
    const before = fixture.queries.length;
    await assert.rejects(js(`window.lqtac.execute('SELECT 1',${JSON.stringify(b.id)})`), /no corresponde/);
    assert.equal(fixture.queries.length, before);
    await js(`document.querySelector(${JSON.stringify(row(a.id)+' .connection-power')}).click()`);
    await until(`document.querySelector(${JSON.stringify(row(a.id)+' .power-off')}) && document.querySelector('#sessions-count').textContent==='1'`);
    assert.ok(await js(`!!document.querySelector(${JSON.stringify(row(b.id)+' .power-on')})`));
    await assert.rejects(js(`window.lqtac.activateConnection(${JSON.stringify(a.id)})`), /cerrada/);
    await js(`document.querySelector(${JSON.stringify(row(b.id))}).click()`);
    await until("document.querySelector('#connection-label').textContent==='Servidor B' && !document.querySelector('#run-query').disabled");
    await js(`document.querySelector('#run-query').click()`);
    await until("document.querySelector('#results tbody td')?.textContent==='asterisk'");
    await fixture.close();
    console.log('PASS: persistent connection groups, drag/drop, contextual actions, independent live sessions and query-session guard');
    clearTimeout(timeout); app.exit(0);
  } catch (error) { console.error(error); await fixture.close(); clearTimeout(timeout); app.exit(1); }
});
